package com.arknights.priestess.model;

/**
 * Enum representing the window state.
 */
public enum WindowState {
    /**
     * Normal window state (not maximized or minimized).
     */
    NORMAL,

    /**
     * Maximized window state.
     */
    MAXIMIZED,

    /**
     * Minimized window state (hidden to tray).
     */
    MINIMIZED_TO_TRAY
}
